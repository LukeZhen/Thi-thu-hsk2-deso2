# Tạo js/key.js (đáp án đã mã hoá) từ admin/answer-key.json.
# Chạy lại mỗi khi sửa answer-key.json:  powershell -ExecutionPolicy Bypass -File admin\build-key.ps1
$root = Split-Path -Parent $PSScriptRoot
$json = [System.IO.File]::ReadAllText((Join-Path $PSScriptRoot 'answer-key.json'), [System.Text.Encoding]::UTF8)
$null = $json | ConvertFrom-Json   # kiểm tra JSON hợp lệ
$data = [System.Text.Encoding]::UTF8.GetBytes(($json -replace '\s*\r?\n\s*', ' '))
$k = [System.Text.Encoding]::ASCII.GetBytes('H20902|hsk2|mock-key')
for ($i = 0; $i -lt $data.Length; $i++) { $data[$i] = $data[$i] -bxor $k[$i % $k.Length] }
$b64 = [Convert]::ToBase64String($data)
$out = "/* Encoded answer key - generated by admin/build-key.ps1. Do not edit by hand. */`nwindow.HSK_KEY = '$b64';`n"
[System.IO.File]::WriteAllText((Join-Path $root 'js\key.js'), $out, (New-Object System.Text.UTF8Encoding $false))
"OK -> js\key.js ($($data.Length) bytes)"
